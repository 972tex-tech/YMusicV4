  function fitNumber(value: number, min: number, max: number) {
    if (value > max) return max;
    if (value < min) return min;
    return value;
  }

  const ACTION_LOAD_VIDEO = 0;
  const ACTION_PRELOAD_VIDEO = 1;
  const ACTION_SET_PWR = 2; // set playWhenReady
  const ACTION_SET_PREFER_VIDEO_QUALITY = 3;
  const ACTION_SEEK = 4;
  const ACTION_STOP = 5;
  const ACTION_SET_LOOP = 6;
  const ACTION_SET_PREFER_CAPTION_LANG = 7;
  const ACTION_SET_AUDIO_TRACK = 8;
  const ACTION_SET_CAPTION_VISIBLE = 9;
  const ACTION_SET_VOLUME = 10;
  const ACTION_SET_PLAY_SPEED = 11;
  const ACTION_BULK = 12;
  const ACTION_ADD_WANTED_PLAYER_RES = 13;
  const ACTION_SEEK_TO_LIVE_HEAD = 14;
  const ACTION_SET_SCALE_MODE = 15;
  const ACTION_GET_PO_TOKEN = 16;

  const SCALE_MODE_COVER = 0;
  const SCALE_MODE_FILL = 1;
  // eslint-disable-next-line @typescript-eslint/no-unused-vars
  const SCALE_MODE_CONTAIN = 2;

  const RES_OK = 'ok';
  const RES_ERROR = 'error';
  const PRELOAD_VIDEO_EXPIRE_SECONDS = 60;
  const DEFAULT_PLAYER_VARS = {
    autoplay: true, autonav: false, playmuted: false,
    // suggestedQuality
  };

  window.ymusicAction = function (encodedParams: string): any {
    if (!moviePlayer) {
      wvApi.reportError('!ready', `${ymusicSessionId} ${encodedParams}`);
      return RES_ERROR;
    }

    const params = JSON.parse(encodedParams);
    return handleAction(moviePlayer, params);
  };

  let audioContextHelper: AudioContextHelper | undefined = undefined;

  function handleAction(moviePlayer: any, params: any) {
    debugLog(() => ({ msg: 'handling action', params }));
    switch (params.what) {
      case ACTION_BULK: {
        const { actions } = params;
        if (actions.length) {
          actions.forEach((action: any) => handleAction(moviePlayer, action));
        }
        return RES_OK;
      }
      case ACTION_LOAD_VIDEO: {
        const { videoId, startTimeSeconds, loop, playWhenReady, preferVideoQuality, volume, speed } = params;
        window.handleYtInternalLog?.('info', 'ymix', `load ${videoId} ${startTimeSeconds} ${loop} ${preferVideoQuality} ${speed}`);
        isStopped = false;
        const playerVars: YtPlayerVars = {
          ...DEFAULT_PLAYER_VARS,
          video_id: videoId, start: startTimeSeconds,
          pause_at_start: playWhenReady === false,
        };
        history?.replaceState?.({}, '', `/watch?v=${videoId}`);
        moviePlayer.loadVideoByPlayerVars(playerVars);

        {
          // legacy
          if (typeof loop == 'boolean') {
            moviePlayer.setLoopVideo(loop);
          }
          if (preferVideoQuality != null) {
            setVideoQuality(preferVideoQuality);
          }
          if (typeof volume == 'number' && volume >= 0 && volume <= 1) {
            moviePlayer.setVolume(volume * 100);
          }
          if (typeof speed == 'number') {
            moviePlayer.setPlaybackRate(fitNumber(speed, 0.25, 2));
          }
        }

        if (window.sendPlayerLogRecords) {
          setTimeout(() => {
            wvApi.remoteDebug('webview_player', internalLogRecords.join('\n'));
          }, 10000);
        }
        return RES_OK;
      }
      case ACTION_PRELOAD_VIDEO: {
        const { videoId } = params;
        window.handleYtInternalLog?.('info', 'ymix', `preload ${videoId}`);
        if (!videoId || videoId.length != 11) {
          wvApi.reportError('Invalid params', `${ymusicSessionId} ${JSON.stringify(params)}`);
          return RES_ERROR;
        }
        const playerVars: YtPlayerVars = {
          ...DEFAULT_PLAYER_VARS,
          video_id: videoId,
        };

        moviePlayer.preloadVideoByPlayerVars(playerVars, undefined, PRELOAD_VIDEO_EXPIRE_SECONDS);
        return RES_OK;
      }
      case ACTION_SET_PWR: {
        const { playWhenReady: value } = params;
        if (typeof value != 'boolean') return RES_ERROR;
        if (value) {
          isStopped = false;
          moviePlayer.playVideo();
        } else {
          moviePlayer.pauseVideo();
        }
        return RES_OK;
      }
      case ACTION_SET_PREFER_VIDEO_QUALITY: {
        const { quality } = params;
        setVideoQuality(quality);
        return RES_OK;
      }
      case ACTION_SEEK: {
        const { positionSeconds } = params;
        if (typeof positionSeconds != 'number') return RES_ERROR;
        moviePlayer.seekTo(positionSeconds);
        return RES_OK;
      }
      case ACTION_STOP: {
        moviePlayer.stopVideo();
        isStopped = true;
        return RES_OK;
      }
      case ACTION_SET_LOOP: {
        const { enable } = params;
        if (typeof enable != 'boolean') return RES_ERROR;
        moviePlayer.setLoopVideo(enable);
        return RES_OK;
      }
      case ACTION_SET_PREFER_CAPTION_LANG: {
        // The host re-sends the full config on every change; each handler owns its state diff.
        const { languageCode } = params;
        if (languageCode != preferCaptionLanguage) {
          preferCaptionLanguage = languageCode;
          performCaptionSelection();
        }
        return RES_OK;
      }
      case ACTION_SET_AUDIO_TRACK: {
        const { trackId } = params;
        if (trackId) {
          const availableAudioTracks: any[] = moviePlayer.getAvailableAudioTracks() ?? [];
          for (let i = 0; i < availableAudioTracks.length; i++) {
            const item = availableAudioTracks[i];
            if (item.id == trackId) {
              moviePlayer.setAudioTrack(item);
              break;
            }
          }
        }
        return RES_OK;
      }
      case ACTION_SET_CAPTION_VISIBLE: {
        const { visible } = params;
        const captionWindow = document.getElementById('ytp-caption-window-container');
        if (captionWindow) {
          const target = visible ? 'visible' : 'hidden';
          if (captionWindow.style.visibility != target) {
            captionWindow.style.visibility = target;
          }
        }
        return RES_OK;
      }
      case ACTION_SET_VOLUME: {
        const { volume } = params;
        if (typeof volume !== 'number' || volume < 0 || volume > 1) return RES_ERROR;
        // Diff against the player's ACTUAL volume, not a shadow — the host re-sends the whole
        // config, and the player can move underneath (restored preferences).
        if (Math.round(moviePlayer.getVolume()) != Math.round(volume * 100)) {
          moviePlayer.setVolume(volume * 100);
        }
        return RES_OK;
      }
      case ACTION_SET_PLAY_SPEED: {
        const { speed, pitchSemitones, pitchFactor } = params;
        if (typeof speed !== 'number') return RES_ERROR;
        const fitted = fitNumber(speed, 0.25, 2);
        if (moviePlayer.getPlaybackRate() != fitted) {
          moviePlayer.setPlaybackRate(fitted);
        }

        // Engage the WebAudio pitch path only for a non-default pitch — or to keep an existing
        // helper in sync — creating it reroutes the audio graph and is not worth it for pitch 1.
        const wantsPitch =
          (typeof pitchSemitones == 'number' && pitchSemitones != 0) ||
          (typeof pitchFactor == 'number' && pitchFactor != 1);
        if (wantsPitch || (audioContextHelper && (typeof pitchSemitones == 'number' || typeof pitchFactor == 'number'))) {
          if (audioContextHelper == null) {
            const mediaElement = moviePlayer.querySelector('video');
            if (mediaElement) {
              audioContextHelper = new AudioContextHelper(mediaElement, wvApi);
            }
          }
          if (audioContextHelper) {
            if (typeof pitchSemitones == 'number') {
              audioContextHelper.setPitchSemitones(pitchSemitones);
            } else if (typeof pitchFactor == 'number') {
              audioContextHelper.setPitchFactor(pitchFactor);
            }
          }
        }

        return RES_OK;
      }
      case ACTION_ADD_WANTED_PLAYER_RES: {
        const { videoId } = params;
        wvApi.addWantedPlayerRes(videoId);
        return RES_OK;
      }
      case ACTION_SEEK_TO_LIVE_HEAD: {
        moviePlayer.seekToLiveHead();
        return RES_OK;
      }
      case ACTION_SET_SCALE_MODE: {
        const { scaleMode } = params;
        const videoElement = document.querySelector('video');
        if (videoElement) {
          videoElement.classList.remove('object-fit-cover');
          videoElement.classList.remove('object-fit-fill');
          videoElement.classList.remove('object-fit-contain');
          if (scaleMode == SCALE_MODE_COVER) {
            videoElement.classList.add('object-fit-cover');
          } else if (scaleMode == SCALE_MODE_FILL) {
            videoElement.classList.add('object-fit-fill');
          } else {
            videoElement.classList.add('object-fit-contain');
          }
        }
        return RES_OK;
      }
      case ACTION_GET_PO_TOKEN: {
        const { videoId, timeout } = params;
        if (videoId) {
          window.generatePoTokenForVideo(videoId, timeout > 0 ? timeout : undefined)
            .then(token => wvApi.postMsg(`${ymusicSessionId}_po_token_v2`, {
              videoId, success: true, token,
            }))
            .catch((error) => {
              if (DEBUG) console.error(error);
              wvApi.postMsg(`${ymusicSessionId}_po_token_v2`, {
                videoId, success: false, message: error?.message,
              });
            });
        } else {
          return RES_ERROR;
        }
        return RES_OK;
      }
      default: {
        wvApi.reportError('Unknown action', `${ymusicSessionId} ${JSON.stringify(params)}`);
        return RES_ERROR;
      }
    }
  }

  window.ymusicPlayerReport = function (): string {
    const html = document.documentElement.outerHTML;
    const playerJson = moviePlayer == null ? 'player null' : moviePlayer.getPlayerResponse() || 'response null';
    return html + '\n' + JSON.stringify(playerJson) + '\n\n' + navigator.userAgent + '\nLogs:\n' + internalLogRecords.join('\n');
  };
