  function __setVideoQuality(quality: string) {
    if (window.ytInternalPlayer) {
      window.ytInternalPlayer.setPlaybackQuality(quality);
    } else {
      moviePlayer.setPlaybackQualityRange(quality);
    }
  }

  function setVideoQuality(newQualitySetting: string, force?: boolean) {
    if (DEBUG) console.log(`set quality ${newQualitySetting} ${qualitySetting}`);
    if (validQualitySettings.indexOf(newQualitySetting) < 0) {
      if (DEBUG) console.error(`Invalid quality setting: ${newQualitySetting}`);
      return;
    }

    if (newQualitySetting != qualitySetting) {
      qualitySetting = newQualitySetting;
      __setVideoQuality(newQualitySetting);
    }
  }

  function performCaptionSelection() {
    if (preferCaptionLanguage == 'off') {
      if (moviePlayer.isSubtitlesOn()) moviePlayer.toggleSubtitles();
    } else {
      if (preferCaptionLanguage == null || preferCaptionLanguage == 'und') {
        // do not change anything
        return;
      }
      const track = captionTracks.find(it => it.actualLanguageCode == preferCaptionLanguage);
      if (track != null) {
        moviePlayer.setOption('captions', 'track', track);
      } else {
        moviePlayer.toggleSubtitlesOn();
      }
    }
  }

