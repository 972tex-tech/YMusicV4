import org.jetbrains.kotlin.gradle.dsl.JvmTarget

plugins {
    kotlin("multiplatform")
}

// Generates httpbun.com's current TLS leaf at build time so HttpClientSmokeTests can trust it without
// a hand-maintained fixture (httpbun uses a Let's Encrypt cert that rotates ~every 90 days). We emit
// the stable ISRG Root X1 root (lets curl/OkHttp/NSURLSession build the full chain) plus the freshly
// fetched leaf (lets the headless iOS simulator, whose SecTrust can't validate live public certs,
// trust via the offline host-match fallback). Always re-runs so the leaf stays current; if the fetch
// fails (e.g. offline) it keeps any previously generated file, falling back to root-only.
val httpbunCertsDir = layout.buildDirectory.dir("generated/httpbunCerts")
val generateHttpbunCerts = tasks.register("generateHttpbunCerts") {
    val outDir = httpbunCertsDir
    outputs.dir(outDir)
    outputs.upToDateWhen { false }
    doLast {
        fun fetchDerBase64(command: String): String? = runCatching {
            val proc = ProcessBuilder("bash", "-c", command).start()
            val out = proc.inputStream.bufferedReader().readText().trim()
            proc.waitFor()
            out.takeIf { it.isNotEmpty() }
        }.getOrNull()

        val root = fetchDerBase64(
            "curl -sS https://letsencrypt.org/certs/isrgrootx1.pem | openssl x509 -outform der | base64 | tr -d '\\n'"
        )
        val leaf = fetchDerBase64(
            "echo | openssl s_client -connect httpbun.com:443 -servername httpbun.com 2>/dev/null " +
                "| openssl x509 -outform der | base64 | tr -d '\\n'"
        )
        val outFile = outDir.get().dir("kmphttp").asFile.resolve("HttpbunCerts.kt")
        if (leaf == null || root == null) {
            if (outFile.exists()) {
                logger.warn("generateHttpbunCerts: fetch failed; reusing existing ${outFile.name}")
                return@doLast
            }
            logger.warn("generateHttpbunCerts: fetch failed and no cached certs; iOS smoke tests may fail")
        }
        val certs = listOfNotNull(root, leaf).joinToString(",\n        ") { "\"$it\"" }
        outFile.parentFile.mkdirs()
        outFile.writeText(
            """
            |package kmphttp
            |
            |// GENERATED by :kmpHttp:core:generateHttpbunCerts — do not edit. ISRG Root X1 (stable) +
            |// httpbun.com's current leaf, so the smoke suite trusts httpbun without a stale fixture.
            |internal object HttpbunCerts {
            |    val trustedCaDer: List<String> = listOf(
            |        $certs
            |    )
            |}
            |
            """.trimMargin()
        )
    }
}

kotlin {
    kmpHttpCommonConfig()

    jvm {
        compilerOptions {
            jvmTarget.set(JvmTarget.JVM_17)
        }
    }

    withAppleTargets {
        binaries.framework {
            baseName = "kmpHttp"
            isStatic = true
        }
    }

    withLinuxTargets()

    applyDefaultHierarchyTemplate()

    sourceSets {
        /**
         * commonMain
         * ├── jvmMain
         * └── nonJvmMain
         *     └── nativeMain
         *         ├── appleMain (UrlSession engine)
         *         │   ├── iosMain
         *         │   └── macosMain ─┐
         *         ├── linuxMain ─────┤
         *         └── desktopMain <──┘  (libcurl engine; depends on :kmpHttp:curl)
         */
        val commonMain by getting
        val commonTest by getting {
            kotlin.srcDir(generateHttpbunCerts)
        }

        // Shared non-JVM code (native targets)
        val nonJvmMain by creating {
            dependsOn(commonMain)
            dependencies {
                implementation(Libs.Doist.normalizer)
            }
        }

        val nativeMain by getting {
            dependsOn(nonJvmMain)
        }

        // Desktop-native (linux + macos): the libcurl HTTP engine, built on the :curl wrapper.
        val desktopMain by creating {
            dependsOn(nativeMain)
            dependencies {
                implementation(project(":kmpHttp:curl"))
            }
        }
        // Wire whichever desktop intermediates exist (depends on -PkmpTargets / host).
        listOf("macosMain", "linuxMain").forEach { name ->
            findByName(name)?.dependsOn(desktopMain)
        }

        commonMain.dependencies {
            implementation(Libs.Kotlinx.coroutinesCore)
            implementation(Libs.Kotlinx.dateTime)
            implementation(Libs.Okio.core)
        }

        commonTest.dependencies {
            implementation(kotlin("test"))
            implementation(Libs.Kotlinx.coroutinesTest)
        }

        // Shared non-JVM test code (mirrors nonJvmMain: commonTest <- nonJvmTest <- nativeTest).
        val nonJvmTest by creating { dependsOn(commonTest) }
        val nativeTest by getting { dependsOn(nonJvmTest) }

        // Desktop-native test source set: re-runs the shared SslTest against the explicit
        // CurlKmpHttpClient (so curl SSL is exercised on macOS too, not just Linux).
        val desktopTest by creating { dependsOn(commonTest) }
        listOf("macosTest", "linuxTest").forEach { name ->
            findByName(name)?.dependsOn(desktopTest)
        }

        jvmMain.dependencies {
            api(Libs.OkHttp.core)
        }
    }
}