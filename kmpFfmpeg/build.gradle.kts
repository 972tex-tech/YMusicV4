import org.gradle.internal.os.OperatingSystem
import org.jetbrains.kotlin.gradle.dsl.JvmTarget

plugins {
    kotlin("multiplatform")
    id("com.android.library")
}

// Writes the absolute path of a runnable ffmpeg binary into the test source set so the smoke tests
// can exec a real ffmpeg. We ship a host-runnable binary for macOS (ffmpeg-prebuilt-ymusic/macos/
// ffmpeg) and Linux x86_64 (ffmpeg-prebuilt-ymusic/linux-x86_64/ffmpeg, used by the docker linux-test
// run); on every other host the path is emitted as null and the tests skip themselves. Mirrors
// :kmpHttp:core's generateHttpbunCerts pattern (generated Kotlin on the test source set).
val ffmpegBinary = when {
    OperatingSystem.current().isMacOsX -> rootProject.file("ffmpeg-prebuilt-ymusic/macos/ffmpeg")
    // The docker linux-test image is pinned to linux/amd64, so x86_64 is the only Linux binary we need.
    OperatingSystem.current().isLinux && System.getProperty("os.arch") in listOf("amd64", "x86_64") ->
        rootProject.file("ffmpeg-prebuilt-ymusic/linux-x86_64/ffmpeg")
    else -> null
}
val ffmpegTestData = project.file("testdata")
val generateFfmpegTestConfig = tasks.register("generateFfmpegTestConfig") {
    val outDir = layout.buildDirectory.dir("generated/ffmpegTestConfig")
    outputs.dir(outDir)
    val binPath = ffmpegBinary?.takeIf { it.exists() }?.absolutePath
    val dataDir = ffmpegTestData.absolutePath
    inputs.property("binPath", binPath ?: "")
    inputs.property("dataDir", dataDir)
    doLast {
        fun lit(s: String) = "\"${s.replace("\\", "\\\\").replace("\"", "\\\"")}\""
        val binLiteral = binPath?.let { lit(it) } ?: "null"
        val outFile = outDir.get().dir("kmpffmpeg").asFile.resolve("FfmpegTestConfig.kt")
        outFile.parentFile.mkdirs()
        outFile.writeText(
            """
            |package kmpffmpeg
            |
            |// GENERATED by :kmpFfmpeg:generateFfmpegTestConfig — do not edit. Absolute path of a
            |// host-runnable ffmpeg binary (null when this host has none → tests skip), plus the
            |// directory holding the committed media fixtures under kmpFfmpeg/testdata.
            |internal object FfmpegTestConfig {
            |    val binaryPath: String? = $binLiteral
            |    val testDataDir: String = ${lit(dataDir)}
            |}
            |
            """.trimMargin()
        )
    }
}

kotlin {
    targets.all {
        compilations.all {
            compileTaskProvider.configure {
                compilerOptions {
                    freeCompilerArgs.add("-Xexpect-actual-classes")
                }
            }
        }
    }

    sourceSets.all {
        languageSettings.optIn("kotlin.ExperimentalMultiplatform")
    }

    jvm {
        compilerOptions {
            jvmTarget.set(JvmTarget.JVM_17)
        }
    }

    // Android is a separate target from desktop JVM: it shares the ProcessBuilder runner (jvmCommonMain)
    // but owns the unix-y proxy (LocalServerSocket), which desktop JVM never uses.
    androidTarget {
        compilerOptions {
            jvmTarget.set(JvmTarget.JVM_17)
        }
    }

    // Full target matrix (like kmpHttp) so any consumer — including ones with watchOS/tvOS targets —
    // can depend on this module. The real fork/exec impl runs on macOS + Linux; every non-macOS Apple
    // target (iOS/tvOS/watchOS) is configured but its startProcess() throws (no child processes there).
    withAppleTargets()
    withLinuxTargets()

    applyDefaultHierarchyTemplate()

    sourceSets {
        /**
         * commonMain
         * ├── jvmMain              (ProcessBuilder — covers desktop JVM + Android)
         * └── nativeMain
         *     ├── posixMain        (fork/execve — macOS + Linux)         [real]
         *     └── appleNoProcessMain (iOS/tvOS/watchOS — no child procs)  [throws]
         */
        val commonMain by getting
        val nativeMain by getting

        // Shared by desktop JVM + Android: the ProcessBuilder-based runner (works on both).
        val jvmCommonMain by creating { dependsOn(commonMain) }
        jvmMain.get().dependsOn(jvmCommonMain)
        androidMain.get().dependsOn(jvmCommonMain)

        // Desktop-native (macOS + Linux): one fork/execve-based implementation.
        val posixMain by creating { dependsOn(nativeMain) }
        listOf("macosX64Main", "macosArm64Main", "linuxX64Main", "linuxArm64Main").forEach { name ->
            findByName(name)?.dependsOn(posixMain)
        }

        // Every non-macOS Apple target: child processes are not permitted, so startProcess() throws.
        // (macOS is Apple too but gets the real posixMain impl above, so this can't live in appleMain.)
        val appleNoProcessMain by creating { dependsOn(nativeMain) }
        listOf(
            "iosArm64Main", "iosSimulatorArm64Main", "iosX64Main",
            "tvosArm64Main", "tvosSimulatorArm64Main", "tvosX64Main",
            "watchosArm64Main", "watchosDeviceArm64Main", "watchosSimulatorArm64Main", "watchosX64Main",
        ).forEach { name -> findByName(name)?.dependsOn(appleNoProcessMain) }

        commonMain.dependencies {
            implementation(Libs.Kotlinx.coroutinesCore)
            implementation(Libs.Okio.core)
        }

        val commonTest by getting {
            kotlin.srcDir(generateFfmpegTestConfig)
            dependencies {
                implementation(kotlin("test"))
                implementation(Libs.Kotlinx.coroutinesTest)
            }
        }

        // The single smoke-test class lives here, shared by every target that can actually spawn a
        // process: desktop JVM + desktop-native. It is intentionally NOT in commonTest, because
        // commonTest is also inherited by iOS, where startProcess() throws — the checks would exec the
        // (non-null, host) binary and fail instead of skipping. iosTest sees only commonTest.
        val processTest by creating { dependsOn(commonTest) }
        jvmTest.get().dependsOn(processTest)

        // Shared desktop-native test source set (mirrors posixMain).
        val posixTest by creating { dependsOn(processTest) }
        listOf("macosX64Test", "macosArm64Test", "linuxX64Test", "linuxArm64Test").forEach { name ->
            findByName(name)?.dependsOn(posixTest)
        }
    }
}

