import org.gradle.internal.os.OperatingSystem
import org.jetbrains.kotlin.gradle.dsl.JvmTarget
import java.util.Base64

plugins {
    kotlin("multiplatform")
    // New AGP KMP plugin (replaces `com.android.library` + kotlin `androidTarget {}`, which is
    // deprecated and incompatible with AGP 9). Configured via `kotlin { androidLibrary { } }` below.
    id("com.android.kotlin.multiplatform.library")
}

// Writes the absolute path of a runnable ffmpeg binary into the test source set so the smoke tests
// can exec a real ffmpeg. We ship a host-runnable binary for macOS (ffmpeg-prebuilt-ymusic/macos/
// ffmpeg) and Linux x86_64 (ffmpeg-prebuilt-ymusic/linux-x86_64/ffmpeg, used by the docker linux-test
// run); on every other host the path is emitted as null and the tests skip themselves. Mirrors
// :kmpHttp:core's generateHttpbunCerts pattern (generated Kotlin on the test source set).
val ffmpegBinary = when {
    OperatingSystem.current().isMacOsX -> rootProject.file("ffmpeg-prebuilt-ymusic/macos/ffmpeg")
    // The docker linux-test image is pinned to linux/amd64, so x86_64 is the only Linux binary we need.
    OperatingSystem.current().isLinux && System.getProperty("os.arch") in listOf("amd64", "x86_64") ->
        rootProject.file("ffmpeg-prebuilt-ymusic/linux-x86_64/ffmpeg")
    else -> null
}
val ffmpegTestData = project.file("testdata")
val generateFfmpegTestConfig = tasks.register("generateFfmpegTestConfig") {
    val outDir = layout.buildDirectory.dir("generated/ffmpegTestConfig")
    outputs.dir(outDir)
    val binPath = ffmpegBinary?.takeIf { it.exists() }?.absolutePath
    val dataDir = ffmpegTestData.absolutePath
    inputs.property("binPath", binPath ?: "")
    inputs.property("dataDir", dataDir)
    doLast {
        fun lit(s: String) = "\"${s.replace("\\", "\\\\").replace("\"", "\\\"")}\""
        val binLiteral = binPath?.let { lit(it) } ?: "null"
        val outFile = outDir.get().dir("kmpffmpeg").asFile.resolve("KmpProcessTest.kt")
        outFile.parentFile.mkdirs()
        outFile.writeText(
            """
            |package kmpffmpeg
            |
            |// GENERATED by :kmpFfmpeg:generateFfmpegTestConfig — do not edit. The host concrete
            |// FfmpegSmokeTest: binds the absolute path of a host-runnable ffmpeg binary (null when this
            |// host has none → the inherited checks skip) + the committed media fixtures dir under
            |// kmpFfmpeg/testdata. JUnit/kotlin.test runs the @Test methods inherited from the base.
            |// (The Android device builds its own concrete subclass at runtime — see AndroidSmokeTest.)
            |internal class KmpProcessTest : FfmpegSmokeTest() {
            |    override val config = FfmpegTestConfig(binaryPath = $binLiteral, testDataDir = ${lit(dataDir)})
            |}
            |
            """.trimMargin()
        )
    }
}

// ---- Android instrumented tests: real ffmpeg binary + media fixture ----
// The device tests exec the REAL prebuilt android ffmpeg (shipped as lib/<abi>/libffmpeg.so) and
// round-trip a media fixture through the ymix proxy. The new AGP KMP plugin has no jniLibs.srcDir
// API, so we stage the per-ABI binaries into the jniLibs *convention* dir (src/androidDeviceTest/
// jniLibs, gitignored); and since the plugin doesn't pick up an assets dir either, we embed the
// fixture as base64 in a generated test source. ABIs cover the emulators we run on: arm64-v8a on
// Apple Silicon hosts, x86_64 on x86_64 CI.
val ffmpegAndroidAbis = listOf("arm64-v8a", "x86_64")
val stageFfmpegDeviceTestJni = tasks.register<Copy>("stageFfmpegDeviceTestJni") {
    description = "Stage prebuilt android ffmpeg into the androidDeviceTest jniLibs convention dir."
    into(layout.projectDirectory.dir("src/androidDeviceTest/jniLibs"))
    ffmpegAndroidAbis.forEach { abi ->
        from(rootProject.file("ffmpeg-prebuilt-ymusic/android/$abi/libffmpeg.so")) { into(abi) }
    }
}

val generateAndroidFixtures = tasks.register("generateAndroidFixtures") {
    val outDir = layout.buildDirectory.dir("generated/androidFixtures")
    outputs.dir(outDir)
    // Every committed fixture the device tests need (the smoke checks probe all three containers).
    val fixtures = listOf(
        "sample_with_metadata.flac",
        "sample_with_metadata.m4a",
        "sample_with_metadata.mka",
    ).map { it to ffmpegTestData.resolve(it) }
    fixtures.forEach { (_, f) -> inputs.file(f) }
    doLast {
        val entries = fixtures.joinToString(",\n") { (name, f) ->
            "        \"$name\" to\n            \"${Base64.getEncoder().encodeToString(f.readBytes())}\""
        }
        val outFile = outDir.get().dir("kmpffmpeg").asFile.resolve("FfmpegAndroidFixtures.kt")
        outFile.parentFile.mkdirs()
        outFile.writeText(
            """
            |package kmpffmpeg
            |
            |// GENERATED by :kmpFfmpeg:generateAndroidFixtures — do not edit. The committed
            |// testdata/sample_with_metadata.{flac,m4a,mka} fixtures embedded as base64 (filename ->
            |// base64) so the instrumented tests can materialize them on the device without an assets dir.
            |internal object FfmpegAndroidFixtures {
            |    val filesBase64: Map<String, String> = mapOf(
            |$entries,
            |    )
            |}
            |
            """.trimMargin()
        )
    }
}

kotlin {
    targets.all {
        compilations.all {
            compileTaskProvider.configure {
                compilerOptions {
                    freeCompilerArgs.add("-Xexpect-actual-classes")
                }
            }
        }
    }

    sourceSets.all {
        languageSettings.optIn("kotlin.ExperimentalMultiplatform")
    }

    jvm {
        compilerOptions {
            jvmTarget.set(JvmTarget.JVM_17)
        }
    }

    // Android is a separate target from desktop JVM: it shares the ProcessBuilder runner (jvmCommonMain)
    // but owns the ymix proxy (LocalServerSocket), which desktop JVM never uses. Uses the new AGP KMP
    // plugin; the old top-level `android {}` block + `androidTarget {}` are gone (deprecated in AGP 9).
    androidLibrary {
        namespace = "kmpffmpeg"
        compileSdk = Versions.compileSdk
        minSdk = Versions.minSdk
        // The instrumented tests exec a real ffmpeg binary shipped as lib/<abi>/libffmpeg.so. exec()
        // needs a real file on disk, so force the (test) APK to extract native libs into
        // nativeLibraryDir instead of mmap-ing them out of the APK (extractNativeLibs=false default).
        packaging { jniLibs { useLegacyPackaging = true } }
        @Suppress("DEPRECATION") // android KMP compilation exposes jvmTarget only via this accessor
        compilations.configureEach {
            compilerOptions.configure { jvmTarget.set(JvmTarget.JVM_17) }
        }
        // Instrumented (on-device) tests for the ymix server (needs the Android runtime). Gradle
        // Managed Devices pin the matrix to Android 7 (API 24, our minSdk) and Android 11 (API 30) —
        // auto-provisioned aosp emulators. Run the whole matrix with:
        //   ./gradlew :kmpFfmpeg:androidYmixGroupGroupAndroidDeviceTest
        // or one level, e.g. ./gradlew :kmpFfmpeg:android7Api24AndroidDeviceTest
        // (API 24 needs android.experimental.testOptions.managedDevices.allowOldApiLevelDevices, set
        //  in gradle.properties.)
        withDeviceTest {
            instrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
            managedDevices {
                allDevices {
                    create<com.android.build.api.dsl.ManagedVirtualDevice>("android7Api24") {
                        device = "Pixel 2"
                        apiLevel = 24
                        // google_apis (x86_64) — API 24's only image with an ABI we ship a libffmpeg.so
                        // for. The "aosp" source resolves to a 32-bit-x86 image (no matching binary, and
                        // no HW accel on Apple Silicon). Emulated x86_64 here, so slower than arm64 API 30.
                        systemImageSource = "google_apis"
                    }
                    create<com.android.build.api.dsl.ManagedVirtualDevice>("android11Api30") {
                        device = "Pixel 2"
                        apiLevel = 30
                        systemImageSource = "aosp"
                    }
                }
                groups {
                    create("androidYmixGroup") {
                        targetDevices.add(allDevices.getByName("android7Api24"))
                        targetDevices.add(allDevices.getByName("android11Api30"))
                    }
                }
            }
        }
    }

    // Full target matrix (like kmpHttp) so any consumer — including ones with watchOS/tvOS targets —
    // can depend on this module. The real fork/exec impl runs on macOS + Linux; every non-macOS Apple
    // target (iOS/tvOS/watchOS) is configured but its startProcess() throws (no child processes there).
    withAppleTargets()
    withLinuxTargets()

    applyDefaultHierarchyTemplate()

    sourceSets {
        /**
         * commonMain
         * ├── jvmCommonMain       (ProcessBuilder — covers desktop JVM + Android)
         * └── nativeMain
         *     ├── posixMain        (fork/execve — macOS + Linux)         [real]
         *     └── appleNoProcessMain (iOS/tvOS/watchOS — no child procs)  [throws]
         */
        val commonMain by getting {
            dependencies {
                implementation(project(":kmpCommon"))
                implementation(Libs.Kotlinx.coroutinesCore)
                implementation(Libs.Okio.core)
            }
        }
        val nativeMain by getting

        // Shared by desktop JVM + Android: the ProcessBuilder-based runner (works on both).
        val jvmCommonMain by creating {
            dependsOn(commonMain)
        }
        jvmMain.get().dependsOn(jvmCommonMain)
        androidMain.get().dependsOn(jvmCommonMain)

        // Desktop-native (macOS + Linux): one fork/execve-based implementation.
        val posixMain by creating { dependsOn(nativeMain) }
        listOf("macosX64Main", "macosArm64Main", "linuxX64Main", "linuxArm64Main").forEach { name ->
            findByName(name)?.dependsOn(posixMain)
        }

        // Every non-macOS Apple target: child processes are not permitted, so startProcess() throws.
        // (macOS is Apple too but gets the real posixMain impl above, so this can't live in appleMain.)
        val appleNoProcessMain by creating { dependsOn(nativeMain) }
        listOf(
            "iosArm64Main", "iosSimulatorArm64Main", "iosX64Main",
            "tvosArm64Main", "tvosSimulatorArm64Main", "tvosX64Main",
            "watchosArm64Main", "watchosDeviceArm64Main", "watchosSimulatorArm64Main", "watchosX64Main",
        ).forEach { name -> findByName(name)?.dependsOn(appleNoProcessMain) }

        val commonTest by getting {
            dependencies {
                implementation(kotlin("test"))
                implementation(Libs.Kotlinx.coroutinesTest)
            }
        }

        // The shared smoke suite — the abstract FfmpegSmokeTest (its @Test methods), the check bodies,
        // and the FfmpegTestConfig — lives here, run by EVERY target that can spawn a process: desktop
        // JVM, desktop-native, AND the Android device. NOT in commonTest (iOS inherits that and can't
        // exec). The host concrete subclass (KmpProcessTest) is generated into jvmTest/posixTest; the
        // Android one (AndroidSmokeTest) is in androidDeviceTest, which shares these files by srcDir
        // (below) because its source-set tree can't dependsOn processTest under the AGP KMP plugin.
        val processTest by creating { dependsOn(commonTest) }
        val processTestDir = "src/processTest/kotlin"

        // Host `actual` of FfmpegTestConfig = the build-time generated paths. Added straight to each
        // host leaf (jvm + the shared native set) rather than a shared intermediate, since one source
        // set can't bridge the jvm and native target trees. Android supplies its own runtime `actual`.
        jvmTest.get().apply {
            dependsOn(processTest)
            kotlin.srcDir(generateFfmpegTestConfig)
        }

        // Shared desktop-native test source set (mirrors posixMain).
        val posixTest by creating {
            dependsOn(processTest)
            kotlin.srcDir(generateFfmpegTestConfig)
        }
        listOf("macosX64Test", "macosArm64Test", "linuxX64Test", "linuxArm64Test").forEach { name ->
            findByName(name)?.dependsOn(posixTest)
        }

        // Instrumented (on-device) tests. Inherits processTest, so the shared [KmpProcessTest] smoke
        // class runs on the emulator too (against the on-device ffmpeg + materialized fixtures, via the
        // Android FfmpegTestConfig actual below). Plus the Android-only ymix server tests
        // (FfYmixProtocolServerTest, FfmpegRealBinaryTest).
        val androidDeviceTest by getting {
            // Share the smoke suite by physical source (can't dependsOn processTest across trees); the
            // concrete AndroidSmokeTest + the ymix server tests live in this set's own dir.
            kotlin.srcDir(processTestDir)
            kotlin.srcDir(generateAndroidFixtures) // embedded base64 media fixtures
            dependencies {
                implementation(kotlin("test"))            // FfmpegSmokeTest uses kotlin.test.Test
                implementation(Libs.Kotlinx.coroutinesTest) // …and runTest
                implementation(Libs.Testing.junitExt)
                implementation("androidx.test:runner:1.6.2")
            }
        }
    }

    // Stage the ffmpeg binaries into the jniLibs convention dir before anything reads it — both the
    // device-test compile and the JNI-merge-into-APK step (the latter consumes the dir directly, so it
    // needs the dependency declared or Gradle fails the build on the undeclared producer/consumer link).
    tasks.named("compileAndroidDeviceTest").configure { dependsOn(stageFfmpegDeviceTestJni) }
    tasks.matching { it.name == "mergeAndroidDeviceTestJniLibFolders" }
        .configureEach { dependsOn(stageFfmpegDeviceTestJni) }
}

